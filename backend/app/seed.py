def seed(db: OrmSession) -> None:
    """Наполнение БД, если таблицы пусты; затем дозаполнение эмбеддингов."""
    if db.scalar(select(User).limit(1)) is None:
        db.add_all(
            User(
                email=email,
                full_name=full_name,
                group_name=group,
                role=role,
                password_hash=auth.hash_password(PASSWORD_BY_ROLE[role]),
            )
            for email, full_name, group, role in USERS
        )
    if db.scalar(select(Service).limit(1)) is None:
        db.add_all(
            Service(name=name, check_type=check_type, state=state)
            for name, check_type, state in SERVICES
        )
    if db.scalar(select(KbArticle).limit(1)) is None:
        db.add_all(
            KbArticle(kind=kind, title=title, topic=topic, body=body,
                      source="seed", confirmed=True)
            for kind, title, topic, body in KB_ARTICLES
        )
    db.commit()
    index_pending_articles(db)


def index_pending_articles(db: OrmSession) -> int:
    """Индексация эмбеддингов — делегируется в app.kb (T029): одна реализация
    для сидирования и будущего подтверждения статей оператором (US7, FR-063)."""
    return kb.index_pending_articles(db)
